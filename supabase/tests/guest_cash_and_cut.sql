-- Real database permissions and transitions; wrap in BEGIN/ROLLBACK.
do $$
declare owner_id uuid:=gen_random_uuid(); cashier_id uuid:=gen_random_uuid(); stranger_id uuid:=gen_random_uuid();
 product_id uuid;table_id bigint;items jsonb;a jsonb;b jsonb;c jsonb;d jsonb;e jsonb;f jsonb;paid_result jsonb;cut jsonb;result jsonb;blocked boolean;
begin
 insert into auth.users(id,email,raw_user_meta_data) values
 (owner_id,'qa-'||owner_id||'@example.invalid','{"role":"negocio","business_name":"Guest cash QA"}'),
 (cashier_id,'qa-'||cashier_id||'@example.invalid','{"full_name":"Cashier"}'),
 (stranger_id,'qa-'||stranger_id||'@example.invalid','{"full_name":"Other"}');
 update public.profiles set guest_pickup_enabled=true,payment_cash=true,payment_online=false,mercado_pago_connected=false,open_time=null,close_time=null where id=owner_id;
 insert into public.products(restaurant_id,name,price,is_available) values(owner_id,'Cash meal',25,true) returning id into product_id;
 insert into public.restaurant_tables(restaurant_id,name) values(owner_id,'QA table') returning id into table_id;
 insert into public.restaurant_staff(restaurant_id,user_id,staff_role,is_active,can_close_accounts,can_view_kitchen) values(owner_id,cashier_id,'cashier',true,true,false);
 items:=jsonb_build_array(jsonb_build_object('id',product_id,'qty',2));
 assert (select guest_pickup_enabled and payment_cash and not payment_online from public.public_qr_restaurants where id=owner_id),'Cash-only guest menu unavailable';
 assert not has_function_privilege('authenticated','public.create_guest_pickup_order(text,text,uuid,jsonb,text,text)','EXECUTE');
 execute 'set local role service_role';
 a:=public.create_guest_pickup_order(repeat('1',64),repeat('2',64),owner_id,items,'Ana','cash');
 assert a->>'payment_status'='pending' and a->>'payment_method'='cash';
 assert (a->>'payment_before_kitchen')::boolean;
 assert a->>'payment_expires_at' is null,'Cash wrongly has online payment expiry';
 assert (select count(*)=0 from public.kitchen_tickets where order_id=(a->>'id')::bigint),'Cash entered kitchen before payment';
 blocked:=false;
 begin update public.orders set status='preparando' where id=(a->>'id')::bigint;exception when raise_exception then blocked:=true;end;
 assert blocked,'Direct status transition bypassed payment';
 blocked:=false;
 begin perform public.create_guest_pickup_order(repeat('1',64),repeat('2',64),owner_id,items,'Ana','mercado_pago');exception when raise_exception then blocked:=true;end;
 assert blocked,'Request changed payment method on retry';
 update public.profiles set payment_cash=false where id=owner_id;
 blocked:=false;
 begin perform public.create_guest_pickup_order(repeat('3',64),repeat('2',64),owner_id,items,'Bea','cash');exception when raise_exception then blocked:=true;end;
 assert blocked,'Disabled cash method accepted';
 update public.profiles set payment_cash=true where id=owner_id;
 b:=public.create_guest_pickup_order(repeat('3',64),repeat('2',64),owner_id,items,'Bea','cash');
 update public.profiles set payment_online=true,mercado_pago_connected=true where id=owner_id;
 c:=public.create_guest_pickup_order(repeat('4',64),repeat('2',64),owner_id,items,'Caro','mercado_pago');
 execute 'reset role';
 execute 'set local role authenticated';
 perform set_config('request.jwt.claim.sub',stranger_id::text,true);
 blocked:=false;
 begin perform public.register_pos_payment_v2((a->>'id')::bigint,'cash',50,0,100);exception when raise_exception then blocked:=true;end;
 assert blocked,'Stranger registered payment';
 blocked:=false;
 begin perform public.cancel_order((a->>'id')::bigint,'Cancel');exception when raise_exception then blocked:=true;end;
 assert blocked,'Null guest customer allowed a stranger to cancel';
 blocked:=false;
 begin perform public.cancel_order((c->>'id')::bigint,'Cancel');exception when raise_exception then blocked:=true;end;
 assert blocked,'Null online customer allowed a stranger to cancel';
 perform set_config('request.jwt.claim.sub',cashier_id::text,true);
 assert (select count(*)=1 from public.orders where id=(a->>'id')::bigint),'Cashier cannot read pending cash order';
 blocked:=false;
 begin perform public.register_pos_payment_v2((a->>'id')::bigint,'cash',50,0,100);exception when raise_exception then blocked:=true;end;
 assert blocked,'Closed shift accepted payment';
 perform public.open_cash_shift(owner_id,10);
 blocked:=false;
 begin perform public.register_pos_payment_v2((a->>'id')::bigint,'cash',25,0,100);exception when raise_exception then blocked:=true;end;
 assert blocked,'Partial guest payment accepted';
 blocked:=false;
 begin perform public.register_pos_payment_v2((a->>'id')::bigint,'transfer',50,0,null);exception when raise_exception then blocked:=true;end;
 assert blocked,'Guest cash payment changed method';
 blocked:=false;
 begin perform public.register_pos_payment_v2((a->>'id')::bigint,'cash',50,0,10);exception when raise_exception then blocked:=true;end;
 assert blocked,'Insufficient cash accepted';
 paid_result:=public.register_pos_payment_v2((a->>'id')::bigint,'cash',50,0,100);
 assert (paid_result->>'cash_change')::numeric=50 and paid_result->>'payment_status'='approved';
 blocked:=false;
 begin perform public.register_pos_payment_v2((a->>'id')::bigint,'cash',50,0,100);exception when raise_exception then blocked:=true;end;
 assert blocked,'Duplicate payment accepted';
 assert (select count(*)=1 from public.order_payments where order_id=(a->>'id')::bigint),'Duplicate cash ledger entry';
 assert (select count(*)=1 from public.kitchen_tickets where order_id=(a->>'id')::bigint),'Paid guest missing kitchen ticket';
 perform set_config('request.jwt.claim.sub',owner_id::text,true);
 perform public.update_kitchen_ticket_status((select id from public.kitchen_tickets where order_id=(a->>'id')::bigint),'preparando');
 result:=public.update_kitchen_ticket_status((select id from public.kitchen_tickets where order_id=(a->>'id')::bigint),'listo');
 perform set_config('request.jwt.claim.sub',stranger_id::text,true);
 blocked:=false;
 begin perform public.mark_kitchen_ticket_delivered((result->>'id')::bigint);exception when raise_exception then blocked:=true;end;
 assert blocked,'Stranger handed off guest pickup';
 perform set_config('request.jwt.claim.sub',cashier_id::text,true);
 assert (select count(*)=1 from public.kitchen_tickets where order_id=(a->>'id')::bigint and status='listo'),'Cashier cannot see ready guest pickup';
 result:=public.mark_kitchen_ticket_delivered((select id from public.kitchen_tickets where order_id=(a->>'id')::bigint));
 assert result->>'status'='entregado','Cashier cannot deliver pickup';
 blocked:=false;
 begin perform public.mark_kitchen_ticket_delivered((result->>'id')::bigint);exception when raise_exception then blocked:=true;end;
 assert blocked,'Duplicate handoff accepted';
 execute 'reset role';
 assert (select count(*)=1 from public.order_audit_logs where order_id=(a->>'id')::bigint and action='kitchen_ticket_delivered'),'Duplicate delivery audit';
 execute 'set local role authenticated';

 assert (select count(*)=0 from public.kitchen_tickets where order_id in ((b->>'id')::bigint,(c->>'id')::bigint));
 result:=public.get_open_cash_shift_summary(owner_id);
 assert (result->>'cash_sales')::numeric=50 and (result->>'expected_cash')::numeric=60,'Guest cash not included in shift';
 perform set_config('request.jwt.claim.sub',owner_id::text,true);
 d:=public.create_pos_table_order(owner_id,items,null,'pickup',null,'cash',null,'POS unpaid');
 e:=public.create_pos_table_order(owner_id,items,null,'pickup',null,'cash',null,'POS partial');
 f:=public.create_pos_table_order(owner_id,items,null,'dine_in',table_id,'cash',null,null);
 perform public.register_pos_payment_v2((e->>'id')::bigint,'cash',20,0,20);
 blocked:=false;
 begin perform public.close_cash_shift(owner_id,80,null);exception when raise_exception then blocked:=true;end;
 assert blocked,'Partial pickup and open table did not block close';
 assert (select status='pendiente' from public.orders where id=(b->>'id')::bigint),'Failed cut partially cancelled requests';
 perform public.register_pos_payment_v2((e->>'id')::bigint,'cash',30,0,30);
 perform public.register_pos_payment_v2((f->>'id')::bigint,'cash',50,0,50);
 cut:=public.close_cash_shift(owner_id,160,null);
 assert (cut->>'cancelled_pickup_count')::integer=3,'Cut did not cancel all unpaid pickup sources';
 assert (cut->>'cash_sales')::numeric=150 and (cut->>'expected_cash')::numeric=160,'Cut cash total mismatch';
 assert (select count(*)=3 from public.orders where id in ((b->>'id')::bigint,(c->>'id')::bigint,(d->>'id')::bigint) and status='cancelado');
 assert (select status='cancelado' from public.kitchen_tickets where order_id=(d->>'id')::bigint),'Cancelled POS ticket remains in kitchen';
 assert (select count(*)=3 from public.orders where id in ((a->>'id')::bigint,(e->>'id')::bigint,(f->>'id')::bigint) and payment_status='approved' and status<>'cancelado'),'Paid orders were removed';
 execute 'reset role';
 assert (select count(*)=3 from public.order_audit_logs where restaurant_id=owner_id and action='cancelled_at_cash_close'),'Cut cancellation audit missing';
 execute 'set local role service_role';
 result:=public.reconcile_order_payment((c->>'id')::bigint,jsonb_build_object('id','qa-late-'||owner_id,'external_reference',c->>'id','transaction_amount',50,'currency_id','MXN','status','approved','date_last_updated',now()));
 assert (result->>'refund_required')::boolean,'Late approval did not request refund';
 assert (select status='cancelado' and payment_status='pending' from public.orders where id=(c->>'id')::bigint),'Late webhook reopened a cut request';
 assert (select count(*)=0 from public.kitchen_tickets where order_id=(c->>'id')::bigint),'Late approval entered kitchen';
 execute 'reset role';
end $$;
