create or replace function public.open_cash_shift(p_restaurant_id uuid, p_opening_cash numeric)
returns jsonb language plpgsql security definer set search_path = '' as $$
declare v_shift public.cash_shifts%rowtype;
begin
    if not public.has_restaurant_permission(p_restaurant_id, 'close_accounts') then raise exception 'Sin permiso de caja'; end if;
    if p_opening_cash < 0 then raise exception 'El fondo inicial no puede ser negativo'; end if;
    insert into public.cash_shifts(restaurant_id, opened_by, opening_cash)
    values (p_restaurant_id, auth.uid(), p_opening_cash) returning * into v_shift;
    return to_jsonb(v_shift);
exception when unique_violation then raise exception 'Ya existe un turno de caja abierto';
end; $$;

create or replace function public.add_cash_movement(p_restaurant_id uuid, p_type text, p_amount numeric, p_reason text)
returns jsonb language plpgsql security definer set search_path = '' as $$
declare v_shift public.cash_shifts%rowtype; v_movement public.cash_movements%rowtype;
begin
    if not public.has_restaurant_permission(p_restaurant_id, 'close_accounts') then raise exception 'Sin permiso de caja'; end if;
    if p_type not in ('income','expense') or p_amount <= 0 or char_length(trim(p_reason)) < 2 then raise exception 'Movimiento invalido'; end if;
    select * into v_shift from public.cash_shifts where restaurant_id = p_restaurant_id and status = 'open' for update;
    if not found then raise exception 'Primero abre un turno de caja'; end if;
    insert into public.cash_movements(shift_id, restaurant_id, movement_type, amount, reason, created_by)
    values(v_shift.id, p_restaurant_id, p_type, p_amount, left(trim(p_reason),200), auth.uid()) returning * into v_movement;
    return to_jsonb(v_movement);
end; $$;

create or replace function public.close_cash_shift(p_restaurant_id uuid, p_counted_cash numeric, p_notes text default null)
returns jsonb language plpgsql security definer set search_path = '' as $$
declare v_shift public.cash_shifts%rowtype; v_cash_sales numeric := 0; v_movements numeric := 0; v_expected numeric;
begin
    if not public.has_restaurant_permission(p_restaurant_id, 'close_accounts') then raise exception 'Sin permiso de caja'; end if;
    if p_counted_cash < 0 then raise exception 'El efectivo contado no puede ser negativo'; end if;
    select * into v_shift from public.cash_shifts where restaurant_id = p_restaurant_id and status = 'open' for update;
    if not found then raise exception 'No hay turno abierto'; end if;
    select coalesce(sum(amount + tip_amount),0) into v_cash_sales from public.order_payments where shift_id = v_shift.id and payment_method = 'cash';
    select coalesce(sum(case when movement_type='income' then amount else -amount end),0) into v_movements from public.cash_movements where shift_id = v_shift.id;
    v_expected := v_shift.opening_cash + v_cash_sales + v_movements;
    update public.cash_shifts set status='closed', closed_by=auth.uid(), closed_at=now(), counted_cash=p_counted_cash,
        expected_cash=v_expected, difference=p_counted_cash-v_expected, notes=nullif(left(trim(coalesce(p_notes,'')),500),'')
    where id=v_shift.id returning * into v_shift;
    return to_jsonb(v_shift);
end; $$;

create or replace function public.register_pos_payment(p_order_id bigint, p_payment_method text, p_amount numeric, p_tip numeric default 0)
returns jsonb language plpgsql security definer set search_path = '' as $$
declare v_order public.orders%rowtype; v_shift_id uuid; v_paid numeric; v_methods integer;
begin
    select * into v_order from public.orders where id=p_order_id for update;
    if not found or v_order.order_source <> 'pos' then raise exception 'Cuenta no encontrada'; end if;
    if not public.has_restaurant_permission(v_order.restaurant_id,'close_accounts') then raise exception 'Solo caja puede cobrar'; end if;
    if v_order.status='cancelado' or v_order.payment_status='approved' then raise exception 'La cuenta no admite pagos'; end if;
    if p_payment_method not in ('cash','transfer','card_terminal') or p_amount <= 0 or coalesce(p_tip,0) < 0 then raise exception 'Pago invalido'; end if;
    select id into v_shift_id from public.cash_shifts where restaurant_id=v_order.restaurant_id and status='open';
    select coalesce(sum(amount),0) into v_paid from public.order_payments where order_id=p_order_id;
    if p_amount > v_order.total-v_paid+0.01 then raise exception 'El abono supera el saldo pendiente'; end if;
    insert into public.order_payments(order_id,restaurant_id,shift_id,payment_method,amount,tip_amount,received_by)
    values(p_order_id,v_order.restaurant_id,v_shift_id,p_payment_method,p_amount,coalesce(p_tip,0),auth.uid());
    select coalesce(sum(amount),0), count(distinct payment_method) into v_paid,v_methods from public.order_payments where order_id=p_order_id;
    update public.orders set tip_total=(select coalesce(sum(tip_amount),0) from public.order_payments where order_id=p_order_id),
        payment_status=case when v_paid>=total then 'approved' else 'pending' end,
        payment_method=case when v_methods>1 then 'mixed' else p_payment_method end
    where id=p_order_id returning * into v_order;
    insert into public.order_audit_logs(order_id,restaurant_id,action,details,actor_id)
    values(p_order_id,v_order.restaurant_id,'payment',jsonb_build_object('method',p_payment_method,'amount',p_amount,'tip',coalesce(p_tip,0)),auth.uid());
    return to_jsonb(v_order)||jsonb_build_object('paid_total',v_paid,'remaining',greatest(v_order.total-v_paid,0));
end; $$;

create or replace function public.append_pos_order_items(p_order_id bigint, p_items jsonb, p_notes text default null)
returns jsonb language plpgsql security definer set search_path = '' as $$
declare v_order public.orders%rowtype; v_item jsonb; v_product public.products%rowtype; v_qty integer; v_added jsonb:='[]'::jsonb; v_total numeric:=0;
begin
    select * into v_order from public.orders where id=p_order_id for update;
    if not found or v_order.order_source<>'pos' or v_order.payment_status='approved' or v_order.status='cancelado' then raise exception 'La cuenta no esta abierta'; end if;
    if exists(select 1 from public.order_payments where order_id=p_order_id) then raise exception 'No se pueden agregar productos despues de iniciar el cobro'; end if;
    if not public.has_restaurant_permission(v_order.restaurant_id,'create_orders') then raise exception 'Sin permiso para agregar productos'; end if;
    if jsonb_typeof(p_items)<>'array' or jsonb_array_length(p_items)<1 then raise exception 'Agrega productos'; end if;
    for v_item in select value from jsonb_array_elements(p_items) loop
        v_qty := (v_item->>'qty')::integer;
        select * into v_product from public.products where id::text=v_item->>'id' and restaurant_id=v_order.restaurant_id and is_available;
        if not found or v_qty<1 or v_qty>50 then raise exception 'Producto o cantidad invalida'; end if;
        v_added:=v_added||jsonb_build_array(jsonb_build_object('id',v_product.id,'nombre',v_product.name,'price',v_product.price,'qty',v_qty,'station_id',v_product.kitchen_station_id));
        v_total:=v_total+v_product.price*v_qty;
    end loop;
    update public.orders set items=items||v_added,total=total+v_total,notes=coalesce(nullif(left(trim(coalesce(p_notes,'')),500),''),notes),status='pendiente'
    where id=p_order_id returning * into v_order;
    insert into public.order_audit_logs(order_id,restaurant_id,action,details,actor_id) values(p_order_id,v_order.restaurant_id,'items_added',jsonb_build_object('items',v_added,'amount',v_total),auth.uid());
    return to_jsonb(v_order);
end; $$;

create or replace function public.transfer_pos_order(p_order_id bigint, p_table_id bigint, p_waiter_id uuid default null)
returns jsonb language plpgsql security definer set search_path = '' as $$
declare v_order public.orders%rowtype; v_waiter_name text;
begin
    select * into v_order from public.orders where id=p_order_id for update;
    if not found or v_order.order_source<>'pos' or v_order.payment_status='approved' then raise exception 'Cuenta no disponible'; end if;
    if not public.has_restaurant_permission(v_order.restaurant_id,'close_accounts') then raise exception 'Solo caja puede transferir cuentas'; end if;
    if p_table_id is not null and not exists(select 1 from public.restaurant_tables where id=p_table_id and restaurant_id=v_order.restaurant_id and is_active) then raise exception 'Mesa invalida'; end if;
    if p_waiter_id is not null then select full_name into v_waiter_name from public.profiles where id=p_waiter_id; end if;
    if p_waiter_id is not null and not exists(select 1 from public.restaurant_staff where restaurant_id=v_order.restaurant_id and user_id=p_waiter_id and is_active and can_create_orders) then raise exception 'Mesero invalido'; end if;
    update public.orders set table_id=p_table_id,service_type=case when p_table_id is null then 'pickup' else 'dine_in' end,
        created_by=coalesce(p_waiter_id,created_by),waiter_name=coalesce(v_waiter_name,waiter_name)
    where id=p_order_id returning * into v_order;
    insert into public.order_audit_logs(order_id,restaurant_id,action,details,actor_id) values(p_order_id,v_order.restaurant_id,'transferred',jsonb_build_object('table_id',p_table_id,'waiter_id',p_waiter_id),auth.uid());
    return to_jsonb(v_order);
end; $$;

create or replace function public.split_pos_order(p_order_id bigint, p_items jsonb)
returns jsonb language plpgsql security definer set search_path = '' as $$
declare v_order public.orders%rowtype; v_new public.orders%rowtype; v_item jsonb; v_requested integer; v_original integer; v_selected jsonb:='[]'::jsonb; v_remaining jsonb:='[]'::jsonb; v_split_total numeric:=0;
begin
    select * into v_order from public.orders where id=p_order_id for update;
    if not found or v_order.order_source<>'pos' or v_order.payment_status='approved' then raise exception 'Cuenta no disponible'; end if;
    if not public.has_restaurant_permission(v_order.restaurant_id,'close_accounts') then raise exception 'Solo caja puede dividir cuentas'; end if;
    if v_order.discount_total>0 then raise exception 'Divide la cuenta antes de aplicar un cupon'; end if;
    if exists(select 1 from public.order_payments where order_id=p_order_id) then raise exception 'Divide la cuenta antes de registrar abonos'; end if;
    if jsonb_typeof(p_items)<>'array' then raise exception 'Seleccion invalida'; end if;
    for v_item in select value from jsonb_array_elements(v_order.items) loop
        v_original:=coalesce((v_item->>'qty')::integer,0);
        select coalesce(sum((x->>'qty')::integer),0) into v_requested from jsonb_array_elements(p_items) x where x->>'id'=v_item->>'id';
        if v_requested<0 or v_requested>v_original then raise exception 'Cantidad invalida para %',v_item->>'nombre'; end if;
        if v_requested>0 then
            v_selected:=v_selected||jsonb_build_array(v_item||jsonb_build_object('qty',v_requested));
            v_split_total:=v_split_total+((v_item->>'price')::numeric*v_requested);
        end if;
        if v_original-v_requested>0 then v_remaining:=v_remaining||jsonb_build_array(v_item||jsonb_build_object('qty',v_original-v_requested)); end if;
    end loop;
    if jsonb_array_length(v_selected)=0 or jsonb_array_length(v_remaining)=0 then raise exception 'La division debe dejar productos en ambas cuentas'; end if;
    update public.orders set items=v_remaining,total=greatest(total-v_split_total,0) where id=p_order_id returning * into v_order;
    insert into public.orders(customer_id,restaurant_id,restaurant_name,items,total,notes,status,payment_method,payment_status,order_source,service_type,table_id,created_by,waiter_name,inventory_deducted)
    values(v_order.customer_id,v_order.restaurant_id,v_order.restaurant_name,v_selected,v_split_total,v_order.notes,v_order.status,'cash','pending','pos',v_order.service_type,v_order.table_id,v_order.created_by,v_order.waiter_name,v_order.inventory_deducted)
    returning * into v_new;
    insert into public.order_audit_logs(order_id,restaurant_id,action,details,actor_id) values(p_order_id,v_order.restaurant_id,'split',jsonb_build_object('new_order_id',v_new.id,'amount',v_split_total),auth.uid());
    return jsonb_build_object('original_order',to_jsonb(v_order),'new_order',to_jsonb(v_new));
end; $$;

create or replace function public.cancel_pos_order(p_order_id bigint, p_reason text)
returns jsonb language plpgsql security definer set search_path = '' as $$
declare v_order public.orders%rowtype;
begin
    select * into v_order from public.orders where id=p_order_id for update;
    if not found or v_order.order_source<>'pos' then raise exception 'Cuenta no encontrada'; end if;
    if not public.has_restaurant_permission(v_order.restaurant_id,'close_accounts') then raise exception 'Solo caja o propietario pueden cancelar'; end if;
    if char_length(trim(coalesce(p_reason,'')))<4 then raise exception 'Indica el motivo de cancelacion'; end if;
    if exists(select 1 from public.order_payments where order_id=p_order_id) then raise exception 'Una cuenta con pagos requiere devolucion administrativa'; end if;
    update public.orders set status='cancelado',cancelled_reason=left(trim(p_reason),300),closed_at=now() where id=p_order_id returning * into v_order;
    insert into public.order_audit_logs(order_id,restaurant_id,action,reason,actor_id) values(p_order_id,v_order.restaurant_id,'cancelled',v_order.cancelled_reason,auth.uid());
    return to_jsonb(v_order);
end; $$;

create or replace function public.apply_order_coupon(p_order_id bigint, p_code text)
returns jsonb language plpgsql security definer set search_path = '' as $$
declare v_order public.orders%rowtype; v_coupon public.coupons%rowtype; v_discount numeric;
begin
    select * into v_order from public.orders where id=p_order_id for update;
    if not found or not public.has_restaurant_permission(v_order.restaurant_id,'close_accounts') then raise exception 'Cuenta no disponible'; end if;
    if v_order.payment_status='approved' then raise exception 'La cuenta ya fue pagada'; end if;
    select * into v_coupon from public.coupons where restaurant_id=v_order.restaurant_id and upper(code)=upper(trim(p_code)) and is_active
      and (starts_at is null or starts_at<=now()) and (ends_at is null or ends_at>=now());
    if not found then raise exception 'Cupon invalido o vencido'; end if;
    v_discount:=case when v_coupon.discount_type='percent' then round((v_order.total+v_order.discount_total)*least(v_coupon.discount_value,100)/100,2) else least(v_coupon.discount_value,v_order.total+v_order.discount_total) end;
    update public.orders set total=greatest(total+discount_total-v_discount,0),discount_total=v_discount where id=p_order_id returning * into v_order;
    insert into public.order_audit_logs(order_id,restaurant_id,action,details,actor_id) values(p_order_id,v_order.restaurant_id,'coupon',jsonb_build_object('code',v_coupon.code,'discount',v_discount),auth.uid());
    return to_jsonb(v_order);
end; $$;

create or replace function public.adjust_inventory(p_ingredient_id uuid, p_quantity numeric, p_type text, p_reason text default null)
returns jsonb language plpgsql security definer set search_path = '' as $$
declare v_ingredient public.ingredients%rowtype;
begin
    select * into v_ingredient from public.ingredients where id=p_ingredient_id for update;
    if not found or v_ingredient.restaurant_id<>auth.uid() then raise exception 'Ingrediente no encontrado'; end if;
    if p_quantity=0 or p_type not in ('purchase','adjustment','waste') then raise exception 'Movimiento invalido'; end if;
    update public.ingredients set stock=greatest(stock+p_quantity,0),updated_at=now() where id=p_ingredient_id returning * into v_ingredient;
    insert into public.inventory_movements(restaurant_id,ingredient_id,movement_type,quantity,reason,created_by)
    values(v_ingredient.restaurant_id,p_ingredient_id,p_type,p_quantity,left(p_reason,200),auth.uid());
    return to_jsonb(v_ingredient);
end; $$;

create or replace function public.set_product_availability(p_product_id uuid, p_available boolean)
