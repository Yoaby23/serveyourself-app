create or replace function public.list_available_waiters(p_restaurant_id uuid)
returns table(user_id uuid, full_name text, staff_role text) language plpgsql security definer set search_path = '' as $$
begin
    if not public.has_restaurant_permission(p_restaurant_id,'close_accounts') then raise exception 'Sin permiso de caja'; end if;
    return query select s.user_id,p.full_name,s.staff_role from public.restaurant_staff s join public.profiles p on p.id=s.user_id
      where s.restaurant_id=p_restaurant_id and s.is_active and s.can_create_orders order by p.full_name;
end; $$;

create or replace function public.deduct_order_inventory()
returns trigger language plpgsql security definer set search_path = '' as $$
declare v_item jsonb; v_recipe record; v_qty numeric;
begin
    if new.status='preparando' and old.status is distinct from 'preparando' and not new.inventory_deducted then
        for v_item in select value from jsonb_array_elements(new.items) loop
            v_qty:=coalesce((v_item->>'qty')::numeric,0);
            for v_recipe in select r.ingredient_id,r.quantity from public.product_recipes r where r.product_id::text=v_item->>'id' loop
                update public.ingredients set stock=stock-(v_recipe.quantity*v_qty),updated_at=now() where id=v_recipe.ingredient_id;
                insert into public.inventory_movements(restaurant_id,ingredient_id,movement_type,quantity,reason,order_id)
                values(new.restaurant_id,v_recipe.ingredient_id,'sale',-(v_recipe.quantity*v_qty),'Consumo por pedido',new.id);
            end loop;
        end loop;
        new.inventory_deducted:=true;
    end if;
    return new;
end; $$;
drop trigger if exists deduct_order_inventory on public.orders;
create trigger deduct_order_inventory before update of status on public.orders for each row execute function public.deduct_order_inventory();

create or replace function public.sync_order_station_statuses()
returns trigger language plpgsql security definer set search_path = '' as $$
declare v_item jsonb; v_station_id bigint; v_key text;
begin
    for v_item in select value from jsonb_array_elements(new.items) loop
        select kitchen_station_id into v_station_id from public.products where id::text=v_item->>'id';
        v_key:=coalesce(v_station_id::text,'general');
        insert into public.order_station_statuses(order_id,restaurant_id,station_key,kitchen_station_id,status)
        values(new.id,new.restaurant_id,v_key,v_station_id,'pendiente') on conflict(order_id,station_key) do nothing;
    end loop;
    return new;
end; $$;
drop trigger if exists sync_order_station_statuses on public.orders;
create trigger sync_order_station_statuses after insert or update of items on public.orders for each row execute function public.sync_order_station_statuses();

insert into public.order_station_statuses(order_id,restaurant_id,station_key,kitchen_station_id,status)
select o.id,o.restaurant_id,'general',null,o.status from public.orders o
where o.status in ('pendiente','preparando','listo')
on conflict(order_id,station_key) do nothing;

create or replace function public.update_kitchen_station_status(p_order_id bigint, p_station_key text, p_status text)
returns jsonb language plpgsql security definer set search_path = '' as $$
declare v_station public.order_station_statuses%rowtype; v_order_status text;
begin
    select * into v_station from public.order_station_statuses where order_id=p_order_id and station_key=p_station_key for update;
    if not found then raise exception 'Estacion de la comanda no encontrada'; end if;
    if not public.has_restaurant_permission(v_station.restaurant_id,'view_kitchen') then raise exception 'Sin permiso de cocina'; end if;
    if (v_station.status='pendiente' and p_status<>'preparando') or (v_station.status='preparando' and p_status<>'listo') or (v_station.status='listo' and p_status<>'entregado') then raise exception 'Cambio de estado invalido'; end if;
    update public.order_station_statuses set status=p_status,updated_at=now() where order_id=p_order_id and station_key=p_station_key returning * into v_station;
    select case
      when bool_and(status='entregado') then 'entregado'
      when bool_and(status in ('listo','entregado')) then 'listo'
      when bool_or(status in ('preparando','listo','entregado')) then 'preparando'
      else 'pendiente' end into v_order_status
    from public.order_station_statuses where order_id=p_order_id;
    update public.orders set status=v_order_status,
      ready_at=case when v_order_status='listo' then coalesce(ready_at,now()) else ready_at end,
      delivered_at=case when v_order_status='entregado' then coalesce(delivered_at,now()) else delivered_at end,
      closed_at=case when v_order_status='entregado' then coalesce(closed_at,now()) else closed_at end
    where id=p_order_id;
    return to_jsonb(v_station)||jsonb_build_object('order_status',v_order_status);
end; $$;

