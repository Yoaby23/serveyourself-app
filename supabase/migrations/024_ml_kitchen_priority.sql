begin;

alter table public.profiles
    add column if not exists pickup_prep_minutes integer not null default 20,
    add column if not exists dine_in_prep_minutes integer not null default 15;

alter table public.profiles drop constraint if exists profiles_pickup_prep_minutes_check;
alter table public.profiles add constraint profiles_pickup_prep_minutes_check check (pickup_prep_minutes between 5 and 240);
alter table public.profiles drop constraint if exists profiles_dine_in_prep_minutes_check;
alter table public.profiles add constraint profiles_dine_in_prep_minutes_check check (dine_in_prep_minutes between 5 and 240);

alter table public.kitchen_tickets
    add column if not exists started_at timestamptz,
    add column if not exists predicted_prep_minutes numeric(7,2),
    add column if not exists priority_override integer not null default 0,
    add column if not exists priority_note text,
    add column if not exists priority_updated_by uuid references auth.users(id) on delete set null,
    add column if not exists priority_updated_at timestamptz;

alter table public.kitchen_tickets drop constraint if exists kitchen_tickets_priority_override_check;
alter table public.kitchen_tickets add constraint kitchen_tickets_priority_override_check check (priority_override between -1 and 2);

create table if not exists public.kitchen_prep_samples (
    id bigint generated by default as identity primary key,
    ticket_id bigint not null unique references public.kitchen_tickets(id) on delete cascade,
    restaurant_id uuid not null references public.profiles(id) on delete cascade,
    service_type text not null check (service_type in ('pickup','dine_in','delivery')),
    work_units numeric(9,2) not null check (work_units > 0),
    is_peak boolean not null default false,
    prep_minutes numeric(9,2) not null check (prep_minutes > 0 and prep_minutes <= 240),
    created_at timestamptz not null default now()
);

create index if not exists kitchen_prep_samples_model_idx
    on public.kitchen_prep_samples(restaurant_id,service_type,created_at desc);

create table if not exists public.kitchen_ml_models (
    restaurant_id uuid not null references public.profiles(id) on delete cascade,
    service_type text not null check (service_type in ('pickup','dine_in','delivery')),
    sample_count integer not null default 0,
    intercept numeric(10,4) not null default 0,
    per_work_unit numeric(10,4) not null default 0,
    peak_adjustment numeric(10,4) not null default 0,
    mean_absolute_error numeric(10,4),
    trained_at timestamptz not null default now(),
    primary key (restaurant_id,service_type)
);

alter table public.kitchen_prep_samples enable row level security;
alter table public.kitchen_ml_models enable row level security;

drop policy if exists "kitchen_prep_samples_staff_read" on public.kitchen_prep_samples;
create policy "kitchen_prep_samples_staff_read" on public.kitchen_prep_samples
for select to authenticated using (public.has_restaurant_permission(restaurant_id,'view_kitchen'));

drop policy if exists "kitchen_ml_models_staff_read" on public.kitchen_ml_models;
create policy "kitchen_ml_models_staff_read" on public.kitchen_ml_models
for select to authenticated using (public.has_restaurant_permission(restaurant_id,'view_kitchen'));

create or replace function public.kitchen_work_units(p_items jsonb)
returns numeric language sql immutable set search_path='' as $$
select greatest(
    1,
    coalesce((select sum(greatest(coalesce((item->>'qty')::numeric,1),0)) from jsonb_array_elements(coalesce(p_items,'[]'::jsonb)) item),0)
    + jsonb_array_length(coalesce(p_items,'[]'::jsonb)) * 0.35
);
$$;

create or replace function public.retrain_kitchen_model(p_restaurant_id uuid,p_service_type text)
returns void language plpgsql security definer set search_path='' as $$
declare
    v_count integer;
    v_intercept numeric;
    v_slope numeric;
    v_peak numeric;
    v_mae numeric;
begin
    select count(*)::integer,
           coalesce(regr_intercept(prep_minutes::double precision,work_units::double precision),avg(prep_minutes),0),
           coalesce(regr_slope(prep_minutes::double precision,work_units::double precision),0),
           coalesce(avg(prep_minutes) filter(where is_peak)-avg(prep_minutes) filter(where not is_peak),0)
    into v_count,v_intercept,v_slope,v_peak
    from public.kitchen_prep_samples
    where restaurant_id=p_restaurant_id and service_type=p_service_type;

    v_intercept:=greatest(3,least(120,coalesce(v_intercept,0)));
    v_slope:=greatest(0,least(12,coalesce(v_slope,0)));
    v_peak:=greatest(-30,least(60,coalesce(v_peak,0)));

    select avg(abs(prep_minutes-(v_intercept+v_slope*work_units+case when is_peak then v_peak else 0 end)))
    into v_mae
    from public.kitchen_prep_samples
    where restaurant_id=p_restaurant_id and service_type=p_service_type;

    insert into public.kitchen_ml_models(restaurant_id,service_type,sample_count,intercept,per_work_unit,peak_adjustment,mean_absolute_error,trained_at)
    values(p_restaurant_id,p_service_type,v_count,v_intercept,v_slope,v_peak,v_mae,now())
    on conflict(restaurant_id,service_type) do update set
        sample_count=excluded.sample_count,
        intercept=excluded.intercept,
        per_work_unit=excluded.per_work_unit,
        peak_adjustment=excluded.peak_adjustment,
        mean_absolute_error=excluded.mean_absolute_error,
        trained_at=excluded.trained_at;
end;
$$;

create or replace function public.predict_kitchen_minutes(p_ticket_id bigint)
returns numeric language plpgsql stable security definer set search_path='' as $$
declare
    v_ticket public.kitchen_tickets%rowtype;
    v_profile public.profiles%rowtype;
    v_model public.kitchen_ml_models%rowtype;
    v_default numeric;
    v_prediction numeric;
    v_peak boolean;
begin
    select * into v_ticket from public.kitchen_tickets where id=p_ticket_id;
    if not found then raise exception 'Comanda no encontrada';end if;
    select * into v_profile from public.profiles where id=v_ticket.restaurant_id;
    select * into v_model from public.kitchen_ml_models where restaurant_id=v_ticket.restaurant_id and service_type=v_ticket.service_type;

    v_default:=case v_ticket.service_type
        when 'delivery' then coalesce(v_profile.delivery_prep_minutes,30)
        when 'dine_in' then coalesce(v_profile.dine_in_prep_minutes,15)
        else coalesce(v_profile.pickup_prep_minutes,20)
    end;
    v_peak:=extract(hour from v_ticket.created_at at time zone coalesce(v_profile.timezone,'UTC'))::integer between 13 and 16
        or extract(hour from v_ticket.created_at at time zone coalesce(v_profile.timezone,'UTC'))::integer between 19 and 22;

    if coalesce(v_model.sample_count,0)<5 then
        return v_default;
    end if;
    v_prediction:=v_model.intercept+v_model.per_work_unit*public.kitchen_work_units(v_ticket.items)+case when v_peak then v_model.peak_adjustment else 0 end;
    return round(greatest(5,least(120,v_prediction)),2);
end;
$$;

create or replace function public.prepare_kitchen_ticket_timing()
returns trigger language plpgsql security definer set search_path='' as $$
begin
    if new.status='preparando' and old.status is distinct from 'preparando' then
        new.started_at:=coalesce(new.started_at,now());
        new.predicted_prep_minutes:=coalesce(new.predicted_prep_minutes,public.predict_kitchen_minutes(new.id));
    elsif new.status='listo' and old.status is distinct from 'listo' then
        new.started_at:=coalesce(new.started_at,old.started_at,new.created_at);
        new.predicted_prep_minutes:=coalesce(new.predicted_prep_minutes,public.predict_kitchen_minutes(new.id));
        new.ready_at:=coalesce(new.ready_at,now());
    end if;
    return new;
end;
$$;

drop trigger if exists prepare_kitchen_ticket_timing on public.kitchen_tickets;
create trigger prepare_kitchen_ticket_timing
before update of status on public.kitchen_tickets
for each row execute function public.prepare_kitchen_ticket_timing();

create or replace function public.learn_from_kitchen_ticket()
returns trigger language plpgsql security definer set search_path='' as $$
declare
    v_timezone text;
    v_minutes numeric;
    v_hour integer;
begin
    if new.status<>'listo' or old.status='listo' or new.started_at is null or new.ready_at is null then return new;end if;
    v_minutes:=extract(epoch from (new.ready_at-new.started_at))/60.0;
    if v_minutes<1 or v_minutes>240 then return new;end if;
    select coalesce(timezone,'UTC') into v_timezone from public.profiles where id=new.restaurant_id;
    v_hour:=extract(hour from new.started_at at time zone v_timezone)::integer;
    insert into public.kitchen_prep_samples(ticket_id,restaurant_id,service_type,work_units,is_peak,prep_minutes)
    values(new.id,new.restaurant_id,new.service_type,public.kitchen_work_units(new.items),v_hour between 13 and 16 or v_hour between 19 and 22,round(v_minutes,2))
    on conflict(ticket_id) do nothing;
    perform public.retrain_kitchen_model(new.restaurant_id,new.service_type);
    return new;
end;
$$;

drop trigger if exists learn_from_kitchen_ticket on public.kitchen_tickets;
create trigger learn_from_kitchen_ticket
after update of status on public.kitchen_tickets
for each row execute function public.learn_from_kitchen_ticket();

create or replace function public.set_kitchen_ticket_priority(p_ticket_id bigint,p_priority integer,p_note text default null)
returns jsonb language plpgsql security definer set search_path='' as $$
declare v_ticket public.kitchen_tickets%rowtype;
begin
    if p_priority not between -1 and 2 then raise exception 'Prioridad invalida';end if;
    select * into v_ticket from public.kitchen_tickets where id=p_ticket_id for update;
    if not found then raise exception 'Comanda no encontrada';end if;
    if not public.has_restaurant_permission(v_ticket.restaurant_id,'view_kitchen') then raise exception 'Sin permiso para priorizar cocina';end if;
    update public.kitchen_tickets set
        priority_override=p_priority,
        priority_note=nullif(left(trim(coalesce(p_note,'')),160),''),
        priority_updated_by=auth.uid(),
        priority_updated_at=now()
    where id=p_ticket_id returning * into v_ticket;
    return to_jsonb(v_ticket);
end;
$$;

create or replace function public.create_scheduled_pickup_order(p_restaurant_id uuid,p_items jsonb,p_notes text,p_payment_method text,p_scheduled_for timestamptz default null)
returns jsonb language plpgsql security definer set search_path='' as $$
declare v_created jsonb;v_order public.orders%rowtype;
begin
    if p_scheduled_for is not null and (p_scheduled_for<now()+interval '10 minutes' or p_scheduled_for>now()+interval '7 days') then
        raise exception 'El horario debe ser entre 10 minutos y 7 dias';
    end if;
    v_created:=public.create_order_v2(p_restaurant_id,p_items,p_notes,p_payment_method);
    update public.orders set service_type='pickup',scheduled_for=p_scheduled_for
    where id=(v_created->>'id')::bigint and customer_id=auth.uid()
    returning * into v_order;
    if not found then raise exception 'No fue posible programar el pedido';end if;
    return to_jsonb(v_order);
end;
$$;

create or replace function public.update_delivery_location(p_order_id bigint,p_latitude double precision,p_longitude double precision)
returns void language plpgsql security definer set search_path='' as $$
begin
    if not exists(
        select 1 from public.orders
        where id=p_order_id and assigned_driver_id=auth.uid()
          and delivery_status in('accepted','preparing','ready_for_dispatch','picked_up','on_the_way','arrived')
    ) then raise exception 'Pedido no asignado';end if;
    if p_latitude not between -90 and 90 or p_longitude not between -180 and 180 then raise exception 'Ubicacion invalida';end if;
    update public.orders set driver_latitude=p_latitude,driver_longitude=p_longitude,driver_location_at=now() where id=p_order_id;
    update public.delivery_drivers set latitude=p_latitude,longitude=p_longitude,last_location_at=now(),updated_at=now() where user_id=auth.uid();
end;
$$;

create or replace function public.list_kitchen_priority_queue(p_restaurant_id uuid)
returns jsonb language plpgsql stable security definer set search_path='' as $$
declare v_result jsonb;
begin
    if not public.has_restaurant_permission(p_restaurant_id,'view_kitchen') then raise exception 'Sin permiso para ver cocina';end if;

    with base as (
        select t.*,o.scheduled_for,o.assigned_driver_id,o.driver_latitude,o.driver_longitude,o.driver_location_at,o.delivery_status,
               p.latitude as restaurant_latitude,p.longitude as restaurant_longitude,p.pickup_prep_minutes,p.dine_in_prep_minutes,p.delivery_prep_minutes,
               d.vehicle_type,m.sample_count,m.mean_absolute_error,
               coalesce(t.predicted_prep_minutes,public.predict_kitchen_minutes(t.id)) as predicted_minutes,
               coalesce((select jsonb_agg(to_jsonb(s) order by s.id) from public.kitchen_ticket_station_statuses s where s.ticket_id=t.id),'[]'::jsonb) as station_statuses
        from public.kitchen_tickets t
        join public.orders o on o.id=t.order_id
        join public.profiles p on p.id=t.restaurant_id
        left join public.delivery_drivers d on d.user_id=o.assigned_driver_id
        left join public.kitchen_ml_models m on m.restaurant_id=t.restaurant_id and m.service_type=t.service_type
        where t.restaurant_id=p_restaurant_id and t.status in('pendiente','preparando')
    ), eta as (
        select b.*,
            case when b.service_type='delivery' and b.assigned_driver_id is not null
                       and b.driver_latitude is not null and b.driver_longitude is not null
                       and b.restaurant_latitude is not null and b.restaurant_longitude is not null
                       and b.driver_location_at>now()-interval '3 minutes'
                then greatest(1,ceil(
                    (6371*acos(greatest(-1,least(1,
                        cos(radians(b.driver_latitude))*cos(radians(b.restaurant_latitude))*cos(radians(b.restaurant_longitude)-radians(b.driver_longitude))+
                        sin(radians(b.driver_latitude))*sin(radians(b.restaurant_latitude))
                    )))) / case b.vehicle_type when 'walking' then 5 when 'bicycle' then 15 else 25 end * 60
                ))::integer
                else null end as driver_eta_minutes
        from base b
    ), targets as (
        select e.*,
            case
                when service_type='delivery' and driver_eta_minutes is not null then now()+make_interval(mins=>driver_eta_minutes)
                when scheduled_for is not null then scheduled_for
                when service_type='delivery' then created_at+make_interval(mins=>delivery_prep_minutes)
                when service_type='dine_in' then created_at+make_interval(mins=>dine_in_prep_minutes)
                else created_at+make_interval(mins=>pickup_prep_minutes)
            end as target_ready_at
        from eta e
    ), ranked as (
        select x.*,
            x.target_ready_at-make_interval(secs=>round(x.predicted_minutes*60)::integer) as recommended_start_at,
            x.priority_override*1000
                + extract(epoch from (now()-(x.target_ready_at-make_interval(secs=>round(x.predicted_minutes*60)::integer))))/60*10
                + extract(epoch from (now()-x.created_at))/60*0.5 as priority_score
        from targets x
    )
    select coalesce(jsonb_agg(
        to_jsonb(r)-'restaurant_latitude'-'restaurant_longitude'-'pickup_prep_minutes'-'dine_in_prep_minutes'-'delivery_prep_minutes'-'vehicle_type'-'driver_latitude'-'driver_longitude'-'driver_location_at'
        || jsonb_build_object(
            'kitchen_ticket_station_statuses',r.station_statuses,
            'predicted_prep_minutes',round(r.predicted_minutes),
            'priority_reason',case
                when r.priority_override=2 then 'Urgente por cocina'
                when r.priority_override=1 then 'Prioridad alta manual'
                when r.priority_override=-1 then 'Pospuesto por cocina'
                when r.service_type='delivery' and r.driver_eta_minutes is not null then 'Repartidor llega en '||r.driver_eta_minutes||' min'
                when r.service_type='pickup' and r.scheduled_for is not null then 'Recogida programada'
                when r.service_type='delivery' then 'Delivery en espera de repartidor'
                when r.service_type='dine_in' then 'Servicio en mesa'
                else 'Recogida lo antes posible'
            end,
            'model_ready',coalesce(r.sample_count,0)>=5
        ) order by case r.status when 'preparando' then 0 else 1 end,r.priority_score desc,r.created_at
    ),'[]'::jsonb) into v_result
    from ranked r;
    return v_result;
end;
$$;

create or replace view public.public_restaurants as
