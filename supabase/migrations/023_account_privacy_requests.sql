-- Solicitudes verificadas de eliminación de cuenta.
-- Ejecutar después de 022_driver_offer_scheduling.sql.

begin;

create table if not exists public.account_deletion_requests(
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  reason text,
  status text not null default 'pending' check(status in('pending','cancelled','completed','rejected')),
  requested_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  resolved_at timestamptz
);

create unique index if not exists account_deletion_requests_one_pending
on public.account_deletion_requests(user_id) where status='pending';

alter table public.account_deletion_requests enable row level security;
drop policy if exists "account_deletion_requests_read_own" on public.account_deletion_requests;
create policy "account_deletion_requests_read_own"
on public.account_deletion_requests for select to authenticated
using(user_id=auth.uid());

create or replace function public.request_account_deletion(p_reason text default null)
returns jsonb language plpgsql security definer set search_path='' as $$
declare request public.account_deletion_requests%rowtype;
begin
  if auth.uid() is null then raise exception 'Inicia sesión para continuar';end if;

  select * into request
  from public.account_deletion_requests
  where user_id=auth.uid() and status='pending'
  order by requested_at desc limit 1;

  if found then return to_jsonb(request);end if;

  insert into public.account_deletion_requests(user_id,reason)
  values(auth.uid(),nullif(left(trim(coalesce(p_reason,'')),500),''))
  returning * into request;
  return to_jsonb(request);
end; $$;

create or replace function public.cancel_account_deletion_request()
returns jsonb language plpgsql security definer set search_path='' as $$
declare request public.account_deletion_requests%rowtype;
begin
  if auth.uid() is null then raise exception 'Inicia sesión para continuar';end if;

  update public.account_deletion_requests
  set status='cancelled',updated_at=now(),resolved_at=now()
  where user_id=auth.uid() and status='pending'
  returning * into request;

  if not found then raise exception 'No existe una solicitud pendiente';end if;
  return to_jsonb(request);
end; $$;

revoke all on table public.account_deletion_requests from public,anon;
grant select on table public.account_deletion_requests to authenticated;
revoke all on function public.request_account_deletion(text),public.cancel_account_deletion_request() from public,anon;
grant execute on function public.request_account_deletion(text),public.cancel_account_deletion_request() to authenticated;

commit;
